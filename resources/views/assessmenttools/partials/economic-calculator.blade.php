<h4 class="text-color-custom-blue font-weight-bold mb-4">
    Life Cycle Assessment (LCA)
</h4>

<p class="text-3-5">
    Life cycle assessment (LCA) is a method for quantifying the material and energy flows associated with the life cycle of a product or service, and assessing its potential environmental impacts (Jolliet et al. 2016). It works by identifying the activities associated with this product or service over its entire life cycle, “from cradle to grave” (Figure 1).</br></br>It is a multi-criteria approach that is standardized internationally, with the NF EN ISO 14040 standard, and through the Lifecycle Initiative (UN 2022) as part of the UN's environmental programs. LCA enables the impact of a product/process to be assessed at different stages of production, manufacture and use.
</p>

